#include <iostream>  // Для ввода/вывода данных (std::cout, std::cin)
#include <vector>    // Для использования динамического массива (std::vector)
#include <algorithm> // Для алгоритма проверки сортировки (std::is_sorted)
int main() {
    int n1, n2;
    // --- Блок ввода первого списка ---
    std::cout << "--- Ввод первого списка ---\n";
    std::cout << "Количество элементов: ";
    std::cin >> n1;
    std::vector<int> list1(n1);
    std::cout << "Введите элементы через пробел или Enter:\n";
    for (int i = 0; i < n1; ++i) {
        // Выводим номер элемента, чтобы пользователь понимал, что вводит
        std::cout << "  Элемент " << i + 1 << ": ";
        std::cin >> list1[i];
    }
    // --- Блок ввода второго списка ---
    std::cout << "\n--- Ввод второго списка ---\n";
    std::cout << "Количество элементов: ";
    std::cin >> n2;
    std::vector<int> list2(n2);
    std::cout << "Введите элементы через пробел или Enter:\n";
    for (int i = 0; i < n2; ++i) {
        std::cout << "  Элемент " << i + 1 << ": ";
        std::cin >> list2[i];
    }
    // Проверка на сортировку (по возрастанию)
    // std::is_sorted возвращает true, если элементы идут по неубыванию
    bool sorted1 = std::is_sorted(list1.begin(), list1.end());
    bool sorted2 = std::is_sorted(list2.begin(), list2.end());
    // --- Красивый вывод результатов ---
    std::cout << "\n==================================\n";
    std::cout << "РЕЗУЛЬТАТ ПРОВЕРКИ:\n";
    std::cout << "Список 1: " << (sorted1 ? "[Отсортирован]" : "[Не отсортирован]") << "\n";
    std::cout << "Список 2: " << (sorted2 ? "[Отсортирован]" : "[Не отсортирован]") << "\n";
    std::cout << "==================================\n";
    // Итоговый вывод в зависимости от комбинации результатов
    if (sorted1 && sorted2) {
        std::cout << "Вывод: Оба списка отсортированы.\n";
    } else if (sorted1 || sorted2) {
        std::cout << "Вывод: Только один из списков отсортирован.\n";
    } else {
        std::cout << "Вывод: Ни один из списков не отсортирован.\n";
    }
    return 0;
}